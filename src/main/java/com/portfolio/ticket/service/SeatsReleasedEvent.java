package com.portfolio.ticket.service;

/**
 * 회차의 좌석이 하나 이상 풀렸다(취소 또는 선점 만료로 {@code Seat.release()}).
 *
 * <p>{@link ScheduleOpenedEvent} 와 같은 이유로 발행 지점(트랜잭션 안)과 처리 지점(커밋 후)을
 * 나눈다 — 취소·만료는 결제·재고와 직결된 트랜잭션이라, 그 안에서 알림까지 만들면 알림 실패가
 * 취소 자체를 롤백시킬 위험이 생긴다. 커밋된 뒤에만 처리하면 그 위험이 없다.
 *
 * <p>"이 회차가 매진이었다가 방금 풀렸는가"를 여기서 판정하지 않는다. 구독자가 없으면
 * {@link NotificationService} 가 조회 한 번으로 조용히 끝나고, 있으면 알림을 만들고 구독을
 * 지운다(일회성) — 그래서 같은 회차에서 여러 좌석이 잇달아 풀려 이 이벤트가 여러 번 와도
 * 두 번째부터는 구독이 이미 없어 자연히 멈춘다. "정말 매진→비매진 전이였는가"를 미리
 * 계산하는 것보다 이 편이 단순하고, 결과도 같다.
 */
public record SeatsReleasedEvent(Long scheduleId) {}
